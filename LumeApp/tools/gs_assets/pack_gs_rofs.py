"""Pack the LumeGS runtime assets into a LumeEngine ROFS blob.

The plugin embeds its assets as a ROFS (`component_dll.cpp`: GS_BIN/GS_BIN_SIZE)
and registers `gsshaders://`, `gspipelinelayouts://` and
`gsvertexinputdeclarations://` on top of it. The format (reader:
lume/LumeEngine/src/io/rofs_filesystem.cpp, writer: lumeassetcompiler) is a flat
table followed by the file data:

    struct FsEntry { char fname[256]; uint64_t offset; uint64_t size; };  // 272 B
    ... entries ..., zeroed terminator entry, then the data blob.

`offset` is relative to the blob start. Directories are implied by the '/' paths,
so only file entries are needed.

Usage:
  python pack_gs_rofs.py [--repo <root>] [--spv <staging dir>] [--out <dir>]
                         [--empty]
"""

import argparse
import os
import struct
import sys

ENTRY = struct.Struct("<256sQQ")


def collect(repo, spv_dir, empty):
    """Return {rofs_path: absolute source path}."""
    files = {}
    assets = os.path.join(repo, "lume", "LumeGS", "assets", "app")

    def add_tree(src_root, prefix, extra_spv=False):
        if not os.path.isdir(src_root):
            return
        for dirpath, _dirs, names in os.walk(src_root):
            for name in names:
                src = os.path.join(dirpath, name)
                rel = os.path.relpath(src, src_root).replace(os.sep, "/")
                files[prefix + "/" + rel] = src

    if not empty:
        add_tree(os.path.join(assets, "shaders", "shader"), "shaders/shader")
        add_tree(os.path.join(assets, "shaders", "computeshader"), "shaders/computeshader")
        add_tree(os.path.join(assets, "pipelinelayouts"), "pipelinelayouts")
        add_tree(os.path.join(assets, "vertexinputdeclarations"), "vertexinputdeclarations")
        # Generated SPIR-V (same relative path, .spv suffix).
        if spv_dir and os.path.isdir(spv_dir):
            for dirpath, _dirs, names in os.walk(spv_dir):
                for name in names:
                    if not name.endswith(".spv"):
                        continue
                    src = os.path.join(dirpath, name)
                    rel = os.path.relpath(src, spv_dir).replace(os.sep, "/")
                    files["shaders/" + rel] = src
    return files


def build_blob(files, log):
    names = sorted(files)
    table_size = ENTRY.size * (len(names) + 1)  # + zero terminator
    offset = table_size
    entries = []
    data = []
    for name in names:
        with open(files[name], "rb") as f:
            blob = f.read()
        if len(name) > 255:
            raise SystemExit("ROFS name too long: " + name)
        entries.append(ENTRY.pack(name.encode("utf-8"), offset, len(blob)))
        data.append(blob)
        log("pack %-64s %7d bytes" % (name, len(blob)))
        offset += len(blob)
    entries.append(ENTRY.pack(b"", 0, 0))
    return b"".join(entries + data), offset


def write_embed(path, blob):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by LumeApp/tools/gs_assets/pack_gs_rofs.py. */\n")
        f.write('#include <cstdint>\n\n')
        f.write('extern "C" {\n')
        f.write("alignas(16) extern const unsigned char GS_BIN[] = {\n")
        for i in range(0, len(blob), 16):
            chunk = blob[i:i + 16]
            f.write("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
        f.write("};\n")
        f.write("extern const uint64_t GS_BIN_SIZE = %dULL;\n" % len(blob))
        f.write("} // extern \"C\"\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", default=os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "..", "..")))
    parser.add_argument("--spv", default=None)
    parser.add_argument("--out", default=None)
    parser.add_argument("--empty", action="store_true")
    args = parser.parse_args()

    repo = os.path.abspath(args.repo)
    spv_dir = os.path.abspath(args.spv) if args.spv else os.path.join(
        repo, "LumeApp", "entry", ".cxx", "gs_assets")
    out_dir = os.path.abspath(args.out) if args.out else os.path.join(
        repo, "LumeApp", "entry", "src", "main", "cpp", "generated")
    os.makedirs(out_dir, exist_ok=True)

    files = collect(repo, spv_dir, args.empty)
    blob, size = build_blob(files, print)
    write_embed(os.path.join(out_dir, "gs_rofs_embed.cpp"), blob)
    print("ROFS: %d files, %d bytes -> %s" % (len(files), size, out_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
